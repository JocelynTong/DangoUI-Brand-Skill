#!/usr/bin/env node
import assert from "node:assert/strict";
import crypto from "node:crypto";
import fs from "node:fs";
import os from "node:os";
import path from "node:path";
import { spawnSync } from "node:child_process";
import { buildSkillIntegrity, verifySkillIntegrity } from "./verify-brand-skill-integrity.mjs";

const temp = fs.mkdtempSync(path.join(os.tmpdir(), "brand-hardening-"));
const installed = path.join(temp, "installed");
fs.mkdirSync(installed);
fs.writeFileSync(path.join(installed, "SKILL.md"), "clean\n");
fs.writeFileSync(path.join(installed, ".brand-skill-integrity.json"), JSON.stringify(buildSkillIntegrity(installed)));
assert.equal(verifySkillIntegrity(installed).status, "pass");
fs.writeFileSync(path.join(installed, "SKILL.md"), "mixed\n");
assert.throws(() => verifySkillIntegrity(installed), /BRAND_SKILL_MIXED_VERSION/);

const root = path.join(temp, "workflow");
const brand = "timeout-fixture";
const migration = path.join(root, "migrations", brand);
fs.mkdirSync(path.join(root, "skills", "brand"), { recursive: true });
fs.mkdirSync(path.join(root, "skills", "brand", "scripts"), { recursive: true });
fs.mkdirSync(path.join(root, "skills", "brand", "references"), { recursive: true });
fs.mkdirSync(migration, { recursive: true });
fs.cpSync(path.resolve("knowledge"), path.join(root, "knowledge"), { recursive: true });
fs.mkdirSync(path.join(root, "public"), { recursive: true });
fs.cpSync(path.resolve("public/knowledge"), path.join(root, "public", "knowledge"), { recursive: true });
fs.cpSync(path.resolve("skills/brand/scripts"), path.join(root, "skills", "brand", "scripts"), { recursive: true });
fs.copyFileSync(path.resolve("skills/brand/references/decision-reading-policy.json"), path.join(root, "skills", "brand", "references", "decision-reading-policy.json"));
fs.writeFileSync(path.join(root, "skills", "brand", "workflow-contract.json"), JSON.stringify({ roleContractVersion: "test", roles: { hostStrategist: { goal: "test" }, brandApplicationDesigner: { goal: "test" } } }));
fs.writeFileSync(path.join(migration, "goal-contract.json"), JSON.stringify({ sealed: true, mode: "design-host", executionProfile: "fast", goalId: "timeout", thresholds: { maxAttempts: 2 } }));
for (const name of ["brand-evidence.json", "brand-intent.json"]) fs.writeFileSync(path.join(migration, name), "{}\n");
for (const name of ["approved-visual-patterns.json", "component-mapping.json", "dangoui-adapter.json"]) fs.writeFileSync(path.join(migration, name), "{}\n");
const identityPath = `public/assets/brand-assets/${brand}/official.png`;
const identityFile = path.join(root, identityPath);
const identityBytes = Buffer.from("official-identity");
fs.mkdirSync(path.dirname(identityFile), { recursive: true });
fs.writeFileSync(identityFile, identityBytes);
fs.writeFileSync(path.join(migration, "brand-mod.json"), JSON.stringify({ assets: [{ id: "official-identity", role: "brand-identity", sourceKind: "original-site-asset", status: "style-only", localPath: identityPath, sourceSha256: crypto.createHash("sha256").update(identityBytes).digest("hex") }] }));
const startupFile = path.join(migration, "host-startup-page.json");
const hostSource = path.join(root, "host", "src", "pages", "home.vue");
fs.mkdirSync(path.dirname(hostSource), { recursive: true });
fs.writeFileSync(hostSource, "<template><main>search</main></template>\n");
fs.writeFileSync(startupFile, JSON.stringify({ schema: "host-startup-page/v1", hostRoot: "host", route: "/home", sourceFile: "src/pages/home.vue", sourceSha256: crypto.createHash("sha256").update(fs.readFileSync(hostSource)).digest("hex"), scope: "startup-page-only" }));
fs.writeFileSync(path.join(migration, "design-host-preflight.json"), JSON.stringify({ schema: "brand-design-host-preflight/v1", verdict: "pass" }));
const workflow = path.resolve("skills/brand/scripts/brand-subagent-workflow.mjs");
const run = (...args) => spawnSync(process.execPath, [workflow, ...args, "--brand", brand, "--root", root], { encoding: "utf8", env: { ...process.env, BRAND_SKILL_ROOT: path.join(root, "skills", "brand") } });
const prepared = run("prepare");
assert.equal(prepared.status, 0, prepared.stderr || prepared.stdout);
const manifestFile = path.join(migration, "execution-manifest.json");
let manifest = JSON.parse(fs.readFileSync(manifestFile, "utf8"));
assert.equal(manifest.currentStageId, "h5DirectionGeneration-1");
const sha = (file) => crypto.createHash("sha256").update(fs.readFileSync(file)).digest("hex");
const baselineFile = path.join(migration, "host-startup-baseline.json");
assert.ok(fs.existsSync(baselineFile));
assert.equal(JSON.parse(fs.readFileSync(baselineFile, "utf8")).deterministicAnalysis.runtimeMeasurement, "unavailable");
assert.ok(fs.existsSync(path.join(migration, "host-startup-facts.json")));
assert.ok(manifest.deterministicStartupDiagnosis.durationMs >= 0);
assert.ok(manifest.previewTargetAt);
assert.ok(manifest.deadlineAt);
assert.equal(Date.parse(manifest.previewTargetAt) - Date.parse(manifest.createdAt), 300000);
assert.equal(Date.parse(manifest.deadlineAt) - Date.parse(manifest.createdAt), 1200000);
assert.equal(run("next").status, 0);
manifest = JSON.parse(fs.readFileSync(manifestFile, "utf8"));
const h5Stage = manifest.stages.find((item) => item.id === "h5DirectionGeneration-1");
const dispatch = JSON.parse(fs.readFileSync(path.join(root, h5Stage.dispatchPath), "utf8"));
assert.equal(dispatch.timeBudget.scope, "prepare-to-reviewable-three-interactive-h5-directions-with-role-quality-preserved");
assert.equal(dispatch.timeBudget.previewTargetAt, manifest.previewTargetAt);
assert.equal(dispatch.timeBudget.deadlineAt, manifest.deadlineAt);
assert.ok(dispatch.timeBudget.remainingMs > 0 && dispatch.timeBudget.remainingMs <= 1200000);
assert.match(dispatch.timeBudget.targetPolicy, /not permission to skip or terminate required specialist roles/);
assert.equal(dispatch.efficiencyBudget.stageTargetSeconds, 300);
assert.equal(dispatch.efficiencyBudget.stageHardLimitSeconds, null);
assert.equal(dispatch.fastDesignHints.imageGenerationForbidden, false);
assert.equal(dispatch.fastDesignHints.expressiveProduction.required, false);
assert.match(dispatch.fastDesignHints.renderPath.policy, /do not probe for Chromium/);
assert.equal(JSON.parse(fs.readFileSync(path.join(migration, "design-host-route.json"), "utf8")).imageCapability.status, "deferred-until-verified-gap");
const outputFile = path.join(migration, "strategy.json");
fs.writeFileSync(outputFile, "{}\n");
const fakeTimeout = { dispatchId: dispatch.dispatchId, stageId: dispatch.stageId, role: dispatch.role, agentExecutionId: "/root/brand-application-designer", goalSha256: manifest.goalSha256, verdict: "fail", inputs: dispatch.requiredInputs, outputs: [{ path: `migrations/${brand}/strategy.json`, sha256: sha(outputFile) }], blockingFindings: [{ code: "TIME_BUDGET_EXCEEDED", stopObservedAt: new Date(Date.now() + 300000).toISOString() }] };
const fakeReceipt = path.join(migration, "fake-timeout.json");
fs.writeFileSync(fakeReceipt, JSON.stringify(fakeTimeout));
const rejected = run("record", "--receipt", `migrations/${brand}/fake-timeout.json`);
assert.notEqual(rejected.status, 0);
assert.match(rejected.stderr, /ROLE_TIMEOUT_CLAIM_FORBIDDEN/);
assert.equal(JSON.parse(fs.readFileSync(manifestFile, "utf8")).stages.find((item) => item.id === "h5DirectionGeneration-1").status, "dispatched");

// A legacy frozen dispatch retains its finite cap; the new policy does not rewrite history.
const legacyDispatch = structuredClone(dispatch);
legacyDispatch.efficiencyBudget.stageHardLimitSeconds = 600;
fs.writeFileSync(path.join(root, h5Stage.dispatchPath), JSON.stringify(legacyDispatch));
manifest = JSON.parse(fs.readFileSync(manifestFile, "utf8"));
manifest.stages.find((item) => item.id === "h5DirectionGeneration-1").startedAt = new Date(Date.now() - 601000).toISOString();
fs.writeFileSync(manifestFile, JSON.stringify(manifest));
const legacyReceipt = { ...fakeTimeout, verdict: "pass", blockingFindings: [] };
fs.writeFileSync(fakeReceipt, JSON.stringify(legacyReceipt));
const legacyRejected = run("record", "--receipt", `migrations/${brand}/fake-timeout.json`);
assert.notEqual(legacyRejected.status, 0);
assert.match(legacyRejected.stderr, /STAGE_HARD_LIMIT_PASS_FORBIDDEN/);
manifest = JSON.parse(fs.readFileSync(manifestFile, "utf8"));
manifest.deadlineAt = new Date(Date.now() - 1000).toISOString();
fs.writeFileSync(manifestFile, JSON.stringify(manifest));
const timedOut = run("next");
assert.notEqual(timedOut.status, 0);
assert.match(timedOut.stderr, /DESIGN_HOST_FAST_SAFETY_LIMIT_EXCEEDED/);
assert.equal(JSON.parse(fs.readFileSync(manifestFile, "utf8")).status, "timed-out");

assert.ok(sha(manifestFile));
console.log("design-host hardening tests passed");
