import assert from "node:assert/strict";
import fs from "node:fs";
import os from "node:os";
import path from "node:path";
import crypto from "node:crypto";
import { validateTransferReview, installTransferReview, validateTransferApplications } from "./source-transfer-input.mjs";
const temp = fs.mkdtempSync(path.join(os.tmpdir(), "source-transfer-test-"));
const hash = (file) => crypto.createHash("sha256").update(fs.readFileSync(file)).digest("hex");
try {
  const packet = path.join(temp, "evidence-packet.json");
  fs.writeFileSync(packet, JSON.stringify({ producerExecutionId: "/root/evidence", claims: [{ id: "observed", status: "observed" }] }));
  const capture = path.join(temp, "capture.txt"); fs.writeFileSync(capture, "capture");
  const review = { schema: "source-system-transfer/v1", brand: "fixture", status: "independently-reviewed-bounded-candidate", scope: "isolated host trial", reviewer: { identity: "/root/reviewer", independentOfEvidenceProducer: true, independentOfH5Producer: true }, reviewInputs: [{ path: "evidence-packet.json", sha256: hash(packet) }, { path: "capture.txt", sha256: hash(capture) }], consumption: { automatic: false }, preservation: { fullCertificationGranted: false, hostImplementationApproved: false }, rules: [{ id: "transfer.type", status: "permitted-bounded-candidate", scope: "task heading", evidenceRefs: ["observed"], notFor: ["global token"] }], permittedRuleIds: ["transfer.type"], excludedRuleIds: [] };
  const file = path.join(temp, "transfer-reviewed.json");
  const save = () => { fs.writeFileSync(file, JSON.stringify(review)); return { file, sha256: hash(file), brand: "fixture" }; };
  const binding = save();
  assert.equal(validateTransferReview(binding).inputs.length, 2);
  assert.throws(() => validateTransferReview({ ...binding, producers: ["/root/reviewer"] }), /INDEPENDENCE/);
  review.reviewer.identity = "/root/evidence";
  assert.throws(() => validateTransferReview(save()), /INDEPENDENCE/);
  review.reviewer.identity = "/root/reviewer";
  review.reviewInputs[1].path = "../capture.txt";
  assert.throws(() => validateTransferReview(save()), /PATH_UNSAFE/);
  review.reviewInputs[1].path = "capture.txt";
  const valid = save();
  const frozen = installTransferReview({ ...valid, root: path.join(temp, "trial"), stageId: "h5DirectionGeneration-3" });
  assert.equal(frozen.inputs.length, 3);
  fs.writeFileSync(capture, "tampered");
  assert.throws(() => validateTransferReview(valid), /INPUT_HASH_INVALID/);
  const application = { ruleId: "transfer.type", ruleScope: "task heading", region: "task", selector: "#task", sourceReviewSha256: valid.sha256, evidenceRefs: ["observed"], hostReason: "Make the frozen host task heading readable" };
  const check = () => validateTransferApplications({ metadata: { transferRuleApplications: [application] }, source: '<h1 id="task">Task</h1>', review, reviewSha256: valid.sha256, producerExecutionId: "/root/h5" });
  assert.equal(check().length, 1);
  application.ruleId = "invented.rule";
  assert.throws(check, /UNKNOWN_OR_EXCLUDED/);
  process.stdout.write("Source transfer frozen input, tamper, independence, unsafe path and unknown rule tests passed\n");
} finally { fs.rmSync(temp, { recursive: true, force: true }); }
