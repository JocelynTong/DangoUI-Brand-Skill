import {test} from 'node:test';
import assert from 'node:assert/strict';
import fs from 'node:fs';
import path from 'node:path';
import os from 'node:os';
import {prepareLearningOriginals} from './prepare-learning-originals.mjs';
import {writeLearnedBrandInput,consumeLearnedBrandInput} from './learned-brand-input.mjs';
test('originals and guide remain version-bound; scope unchanged and tampering rejected',t=>{
 const root=fs.mkdtempSync(path.join(os.tmpdir(),'learning-originals-test-'));t.after(()=>fs.rmSync(root,{recursive:true,force:true}));
 const dir=path.join(root,'fixture'),pkg=path.join(root,'package');fs.mkdirSync(dir);
 const put=(file,value)=>{fs.mkdirSync(path.dirname(file),{recursive:true});fs.writeFileSync(file,typeof value==='string'?value:JSON.stringify(value));};
 const scope={notFor:['host apply']};
 for(const [name,value]of Object.entries({'brand-mod.json':{manifest:{brand:'fixture',version:'v1',scope},tokens:{dtcg:{}}},'brand-intent.json':{status:'partial',imageIdentityPolicy:{instruction:'original IP'}},'brand-evidence.json':{},'component-mapping.json':{},'dangoui-adapter.json':{}}))put(path.join(dir,name),value);
 for(const name of ['src/button/style.scss','src/search/Search.scss','dist/theme.css','dist/style.css','LICENSE'])put(path.join(pkg,name),'fixture');
 put(path.join(pkg,'package.json'),{name:'dangoui',version:'test'});
 put(path.join(pkg,'src/button/Button.vue'),"import Icon from '../icon/Icon.vue'\nimport {ref} from 'vue'");
 put(path.join(pkg,'src/search/Search.vue'),"import Icon from '../icon/Icon.vue'");
 put(path.join(pkg,'src/icon/Icon.vue'),'<template><span/></template>');
 const result=prepareLearningOriginals(dir,pkg);
 assert.deepEqual(result.externalDependencies,['vue']);
 const mod=JSON.parse(fs.readFileSync(path.join(dir,'brand-mod.json')));assert.deepEqual(mod.manifest.scope,scope);
 assert.equal(mod.componentKits,undefined);
 assert(mod.componentSources[0].files.some(x=>x.path.endsWith('/icon/Icon.vue')));
 assert(fs.readFileSync(path.join(dir,'DESIGN.md'),'utf8').includes('original IP'));
 writeLearnedBrandInput(dir);const packet=consumeLearnedBrandInput(dir);
 assert(!packet.gaps.some(g=>g.code==='DESIGN_MD_NOT_BOUND'));
 assert(packet.gaps.some(g=>g.code==='COMPONENT_RUNTIME_NOT_CERTIFIED'));
 fs.appendFileSync(path.join(dir,'component-originals/dangoui/src/icon/Icon.vue'),'changed');
 assert.throws(()=>consumeLearnedBrandInput(dir),/COMPONENT_SOURCE_HASH_MISMATCH/);
});
