import assert from "node:assert/strict";
import fs from "node:fs";
import os from "node:os";
import path from "node:path";
import crypto from "node:crypto";
import { recoverReference } from "./recover-reference.mjs";
const temp = fs.mkdtempSync(path.join(os.tmpdir(), "recover-reference-test-"));
const root = path.join(temp, "build");
const sourceRoot = path.join(temp, "source");
const hash = (file) => crypto.createHash("sha256").update(fs.readFileSync(file)).digest("hex");
const write = (base, name, bytes) => { const file = path.join(base, name); fs.mkdirSync(path.dirname(file), { recursive: true }); fs.writeFileSync(file, bytes); return file; };
try {
  write(root, "migrations/fixture/prior-direction-index.json", JSON.stringify({ schema: "brand-prior-directions/v1", status: "old-fail", oldRecord: "preserved" }));
  const receipt = write(root, "migrations/fixture/receipts/old.json", "old FAIL");
  const host = write(temp, "host/App.vue", "real host unchanged");
  const asset = write(sourceRoot, "trial/assets/image.png", "image pixels");
  const css = write(sourceRoot, "trial/style.css", '.hero{background:url("assets/image.png")}');
  const html = write(sourceRoot, "trial/index.html", '<link href="style.css" rel="stylesheet"><img src="https://example.test/historical-cover.jpg">');
  const previous = write(sourceRoot, "history/old.html", '<img src="obsolete-missing.png">');
  const master = write(sourceRoot, "approved-master.json", JSON.stringify({ schema: "brand-approved-master/v1", aestheticApproval: "pending", approvalScope: "trial-implementation-only", artifact: { path: "trial/index.html", sha256: hash(html) }, asset: { path: "trial/assets/image.png", sha256: hash(asset) }, supersedes: { path: "history/old.html", sha256: hash(previous) } }));
  const original = { receipt: hash(receipt), host: hash(host), master: hash(master) };
  const args = { root, brand: "fixture", sourceRoot, sourceMaster: "approved-master.json", sourceMasterSha256: hash(master), reason: "User confirmed visual reference only", confirmed: true };
  assert.throws(() => recoverReference({ ...args, confirmed: false }), /EXPLICIT_CONFIRMATION/);
  assert.throws(() => recoverReference({ ...args, sourceMasterSha256: "0".repeat(64) }), /HASH_MISMATCH/);
  fs.renameSync(asset, `${asset}.saved`);
  assert.throws(() => recoverReference(args), /DEPENDENCY_MISSING/);
  fs.renameSync(`${asset}.saved`, asset);
  fs.writeFileSync(css, '.hero{background:url("../../../escape.png")}');
  assert.throws(() => recoverReference(args), /PATH_UNSAFE/);
  fs.writeFileSync(css, '.hero{background:url("assets/image.png")}');
  const assets = path.dirname(asset);
  fs.renameSync(assets, `${assets}-real`); fs.symlinkSync(`${assets}-real`, assets);
  assert.throws(() => recoverReference(args), /SYMLINK_FORBIDDEN/);
  fs.unlinkSync(assets); fs.renameSync(`${assets}-real`, assets);
  const result = recoverReference(args);
  assert.equal(result.scope, "historical-visual-reference-only");
  assert.equal(result.idempotent, false);
  const record = JSON.parse(fs.readFileSync(path.join(root, result.reference.path), "utf8"));
  assert.equal(record.aestheticApproval, "pending");
  assert.equal(record.applyHostApproved, false);
  assert.equal(record.remoteResources.length, 1);
  assert.ok(record.files.some((item) => item.sourcePath === "history/old.html"));
  assert.ok(record.limitations.some((item) => item.includes("Superseded HTML")));
  assert.ok(!record.files.some((item) => item.sourcePath.endsWith("obsolete-missing.png")));
  const copiedMaster = record.files.find((item) => item.sourcePath === "approved-master.json");
  assert.deepEqual(fs.readFileSync(path.join(root, copiedMaster.path)), fs.readFileSync(master));
  assert.equal(recoverReference(args).idempotent, true);
  const index = JSON.parse(fs.readFileSync(path.join(root, "migrations/fixture/prior-direction-index.json"), "utf8"));
  assert.equal(index.oldRecord, "preserved"); assert.equal(index.status, "old-fail"); assert.equal(index.recoveredReferences.length, 1);
  assert.deepEqual({ receipt: hash(receipt), host: hash(host), master: hash(master) }, original);
  fs.writeFileSync(path.join(root, record.artifact.path), "tampered recovery");
  assert.throws(() => recoverReference(args), /RECOVERED_HASH_MISMATCH/);
  process.stdout.write("Reference recovery hashes, dependencies, containment, symlinks, idempotency and preserved history tests passed\n");
} finally { fs.rmSync(temp, { recursive: true, force: true }); }
