import {test} from 'node:test';
import assert from 'node:assert/strict';
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import {writeLearnedBrandInput,consumeLearnedBrandInput,verifyLearnedPrompt} from './learned-brand-input.mjs';
test('learning output preserves exact scopes, unknowns and values; changed sources cannot silently be consumed',t=>{
  const root=fs.mkdtempSync(path.join(os.tmpdir(),'learned-input-'));t.after(()=>fs.rmSync(root,{recursive:true,force:true}));
  const intent={status:'partial',imageIdentityPolicy:{instruction:'Original IP, new illustration allowed'},unresolvedClaims:['motion'],scope:'campaign only'};
  const docs={'brand-mod.json':{manifest:{brand:'fixture',version:'1',scope:{notFor:['global CTA']}},tokens:{dtcg:{action:{$value:'#FF8800'}}}},'brand-intent.json':intent,'brand-evidence.json':{},'component-mapping.json':{mappings:[]},'dangoui-adapter.json':{}};
  for(const [name,value] of Object.entries(docs))fs.writeFileSync(path.join(root,name),JSON.stringify(value));
  const packet=writeLearnedBrandInput(root),consumed=consumeLearnedBrandInput(root);
  verifyLearnedPrompt(`host facts\n<learned-brand-input>\n${packet.promptText}\n</learned-brand-input>\ncreative direction`,packet);
  assert.throws(()=>verifyLearnedPrompt('rewritten brand summary',packet),/LEARNED_INPUT_NOT_USED/);
  assert.throws(()=>verifyLearnedPrompt(`<learned-brand-input>\n${packet.promptText.replace('Original IP','Generic mascot')}\n</learned-brand-input>`,packet),/LEARNED_INPUT_NOT_USED/);
  verifyLearnedPrompt('legacy prompt',undefined);
  assert.equal(consumed.promptSha256,packet.promptSha256);
  assert.deepEqual(JSON.parse(consumed.promptText).intent,intent);
  assert.equal(consumed.learningStatus,'partial');
  assert.deepEqual(JSON.parse(consumed.promptText).scope,{notFor:['global CTA']});
  assert.equal(consumed.sources.length,5);
  assert.equal(consumed.gaps.length,2);
  assert.equal(writeLearnedBrandInput(root).sha256,packet.sha256);
  fs.appendFileSync(path.join(root,'dangoui-adapter.json'),' ');
  assert.throws(()=>consumeLearnedBrandInput(root),/LEARNED_INPUT_STALE/);
  assert.throws(()=>writeLearnedBrandInput(root),/LEARNED_INPUT_CHANGED/);
  const revised=writeLearnedBrandInput(root,{supersede:true});
  assert.notEqual(revised.sourceDigest,packet.sourceDigest);
  const archive=path.join(root,'learning-revisions',packet.sourceDigest);
  assert.equal(JSON.parse(fs.readFileSync(path.join(archive,'learned-brand-input.json'))).sourceDigest,packet.sourceDigest);
  assert.equal(fs.readFileSync(path.join(archive,'dangoui-adapter.json'),'utf8'),'{}');
  assert.equal(consumeLearnedBrandInput(root).sourceDigest,revised.sourceDigest);
});
