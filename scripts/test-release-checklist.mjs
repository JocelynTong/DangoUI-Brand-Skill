import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';
import { parse, compileTemplate } from '@vue/compiler-sfc';
import { ref, computed } from 'vue';
const source = readFileSync(new URL('../src/documents/ReleaseChecklist.vue', import.meta.url), 'utf8');
const { descriptor, errors } = parse(source);
assert.deepEqual(errors, []);
assert.deepEqual(compileTemplate({ source: descriptor.template.content, filename:'ReleaseChecklist.vue', id:'release-test' }).errors, []);
// Execute the component's actual state logic, not a duplicate test implementation.
const script = descriptor.scriptSetup.content.replace(/^import .*;$/gm, '');
const make = () => new Function('ref', 'computed', `${script}\nreturn { checks, remind, message, completed, summarize, reset };`)(ref, computed);
const state = make();
assert.equal(state.completed.value, 0);
state.summarize();
assert.match(state.message.value, /还有 3 项未完成/);
state.checks.value[0].done = true;
assert.equal(state.completed.value, 1);
state.summarize();
assert.match(state.message.value, /还有 2 项未完成：交互完整、适配通过/);
state.checks.value.forEach(item => item.done = true);
state.remind.value = false;
state.summarize();
assert.match(state.message.value, /3 项已完成；离开前提醒关闭。未执行发布/);
state.reset();
assert.equal(state.completed.value, 0);
assert.equal(state.remind.value, false);
assert.equal(make().completed.value, 0);
assert.match(source, /@keydown.space.prevent/);
assert.match(source, /color="site"/);
assert.doesNotMatch(source, /fetch\(|localStorage|setInterval/);
console.log('Release checklist: partial, complete, reminder, reset and fresh-session states passed.');
