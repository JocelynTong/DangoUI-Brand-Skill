import assert from 'node:assert/strict';
import { collectBrandUsage } from './collect-brand-usage.mjs';
const options = { thread: 'thread-a', turn: 'trial-turn', round: 'round-1', category: 'trial' };
const meta = { type: 'session_meta', payload: { id: 'thread-a' } };
const context = turn_id => ({ type: 'turn_context', payload: { turn_id } });
const usage = (n, extra = {}) => ({ input_tokens: n, cached_input_tokens: n / 2, output_tokens: n / 10, reasoning_output_tokens: n / 20, total_tokens: n + n / 10, ...extra });
const event = (total, last) => ({ type: 'event_msg', payload: { type: 'token_count', info: { total_token_usage: total, ...(last ? { last_token_usage: last } : {}) } } });
const collect = (rows, opts = options) => collectBrandUsage(rows.map(JSON.stringify).join('\n'), opts);
const baseline = event(usage(100));
const increment = event(usage(200));
const report = collect([meta, context('dev-turn'), baseline, context('trial-turn'), increment, increment]);
assert.equal(report.modelUsage.inputTokens, 100);
assert.equal(report.modelUsage.cachedInputTokens, 50);
assert.equal(report.modelUsage.outputTokens, 10);
assert.equal(report.modelUsage.reasoningOutputTokens, 5);
assert.equal(report.modelUsage.totalTokens, 110);
assert.equal(report.evidence.duplicateNotifications, 1);
assert.equal(report.imageGenerationUsage.tokens, null);
assert.equal(collect([meta, context('trial-turn'), baseline]).modelUsage.inputTokens, null);
assert.equal(collect([meta, context('trial-turn'), event(usage(100), usage(100))]).modelUsage.inputTokens, 100);
const missing = collect([meta, baseline, context('trial-turn'), event(usage(200, { cached_input_tokens: undefined }))]);
assert.equal(missing.modelUsage.cachedInputTokens, null);
assert.equal(missing.modelUsage.inputTokens, 100);
const reset = collect([meta, increment, context('trial-turn'), baseline, event(usage(200))]);
assert.equal(reset.modelUsage.inputTokens, null);
assert.ok(reset.evidence.reasons.includes('cumulative-counter-reset'));
const bounded = collect([meta, baseline, increment], { ...options, turn: undefined, startLine: 3, endLine: 3 });
assert.equal(bounded.modelUsage.inputTokens, 100);
assert.throws(() => collect([meta], { ...options, thread: 'wrong' }), /does not match/);
assert.throws(() => collect([meta], { ...options, startLine: 1, endLine: 1 }), /exactly one/);
assert.throws(() => collect([meta], { ...options, turn: undefined, startLine: 1, endLine: 9 }), /exceeds/);
assert.equal(collect([meta, context('other'), baseline]).modelUsage.totalTokens, null);
const rpc = n => ({ method: 'thread/tokenUsage/updated', params: { threadId: 'thread-a', turnId: 'trial-turn', tokenUsage: { total: { inputTokens: n, cachedInputTokens: n / 2, outputTokens: n / 10, reasoningOutputTokens: n / 20, totalTokens: n + n / 10 } } } });
const rpcReport = collect([rpc(100), rpc(200)], { ...options, turn: undefined, startLine: 2, endLine: 2 });
assert.equal(rpcReport.modelUsage.totalTokens, 110);
const privateText = collect([meta, baseline, context('trial-turn'), { type: 'response_item', payload: { text: 'PRIVATE SECRET PROMPT' } }, increment]);
assert.ok(!JSON.stringify(privateText).includes('PRIVATE'));
console.log('collect-brand-usage: all assertions passed');
