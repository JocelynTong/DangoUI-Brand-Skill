import assert from "node:assert/strict";
import crypto from "node:crypto";
import fs from "node:fs";
import os from "node:os";
import path from "node:path";
import { spawnSync } from "node:child_process";

const engine = path.resolve("skills/brand/scripts/brand-subagent-workflow.mjs");
const entry = path.resolve("skills/brand/scripts/run-brand-workflow.mjs");
const skillRoot = path.resolve("skills/brand");
const failureVerdict = process.argv.includes("--needs-evidence") ? "needs-evidence" : "fail";
const temp = fs.mkdtempSync(path.join(os.tmpdir(), "retry-h5-"));
const root = path.join(temp, "build");
const host = path.join(temp, "host");
const brand = "fixture";
const migration = path.join(root, "migrations", brand);
const sha = (file) => crypto.createHash("sha256").update(fs.readFileSync(file)).digest("hex");
const write = (name, value) => {
  const file = path.join(migration, name);
  fs.mkdirSync(path.dirname(file), { recursive: true });
  fs.writeFileSync(file, typeof value === "string" ? value : JSON.stringify(value));
  return { path: path.relative(root, file), sha256: sha(file) };
};
const call = (command, ...args) => spawnSync(process.execPath, [engine, command, "--root", root, "--brand", brand, ...args], { encoding: "utf8", env: { ...process.env, BRAND_SKILL_ROOT: skillRoot } });
const pass = (result) => { assert.equal(result.status, 0, result.stderr); return JSON.parse(result.stdout); };
const manifestFile = path.join(migration, "execution-manifest.json");
const manifest = () => JSON.parse(fs.readFileSync(manifestFile, "utf8"));
try {
  fs.mkdirSync(host, { recursive: true });
  fs.writeFileSync(path.join(temp, "run.json"), JSON.stringify({ schema: "brand-artifact-run/v1", status: "active", host }));
  fs.mkdirSync(path.join(root, "src"), { recursive: true });
  fs.writeFileSync(path.join(root, "src", "App.vue"), "<template><input aria-label='search'><article>deck result</article></template>");
  write("goal-contract.json", { sealed: true, mode: "design-host", executionProfile: "fast", goalId: "retry-h5", hostTarget: host });
  for (const name of ["brand-evidence.json", "brand-intent.json", "brand-mod.json"]) write(name, {});
  write("design-host-preflight.json", { schema: "brand-design-host-preflight/v1", verdict: "pass" });
  write("host-startup-page.json", { schema: "host-startup-page/v1", scope: "startup-page-only", route: "/", sourceFile: "src/App.vue", sourceSha256: sha(path.join(root, "src", "App.vue")) });
  pass(call("prepare"));
  pass(call("next"));
  assert.match(call("retry-h5").stderr, /H5_RETRY_EXPLICIT_CONTINUATION_REQUIRED/);
  assert.match(call("retry-h5", "--continue-existing").stderr, /H5_RETRY_FAILED_STAGE_REQUIRED/);
  const activeBeforeTimeout = fs.readFileSync(manifestFile);
  const activeExpired = manifest();
  activeExpired.deadlineAt = new Date(Date.now() - 1000).toISOString();
  fs.writeFileSync(manifestFile, JSON.stringify(activeExpired));
  assert.match(call("next").stderr, /DESIGN_HOST_FAST_SAFETY_LIMIT_EXCEEDED/);
  assert.equal(manifest().status, "timed-out", "a live dispatched stage still observes the safety deadline");
  assert.match(call("retry-h5", "--continue-existing").stderr, /H5_RETRY_FAILED_STAGE_REQUIRED/, "timeout without a failed receipt is not an authorized H5 retry");
  fs.writeFileSync(manifestFile, activeBeforeTimeout);
  const stage = manifest().stages[0];
  const dispatch = JSON.parse(fs.readFileSync(path.join(root, stage.dispatchPath), "utf8"));
  const oldOutput = write("h5-directions/direction-a.html", "<!doctype html><title>failed original</title>");
  const hostInputFile = path.join(root, "host-input", "opcg", "decks", "avatar-receipt-v2.json");
  fs.mkdirSync(path.dirname(hostInputFile), { recursive: true });
  fs.writeFileSync(hostInputFile, '{"status":"frozen"}');
  const hostInputBinding = { path: path.relative(root, hostInputFile), sha256: sha(hostInputFile) };
  const receipt = write("receipts/failed.json", { dispatchId: dispatch.dispatchId, stageId: stage.id, role: stage.role, agentExecutionId: "/root/producer", goalSha256: manifest().goalSha256, verdict: failureVerdict, inputs: dispatch.requiredInputs, outputs: [oldOutput, hostInputBinding], blockingFindings: ["brand composition failed"] });
  pass(call("record", "--receipt", receipt.path));
  const expiredBlocked = manifest();
  expiredBlocked.deadlineAt = new Date(Date.now() - 1000).toISOString();
  fs.writeFileSync(manifestFile, JSON.stringify(expiredBlocked));
  const expiredBlockedBytes = fs.readFileSync(manifestFile);
  const terminalNext = call("next");
  assert.equal(JSON.parse(terminalNext.stdout).status, "blocked");
  assert.deepEqual(fs.readFileSync(manifestFile), expiredBlockedBytes, "next must not turn a receipt-backed terminal FAIL into a timeout");
  pass(call("status"));
  assert.deepEqual(fs.readFileSync(manifestFile), expiredBlockedBytes, "status must preserve terminal FAIL after deadline expiry");
  const failed = manifest().stages[0];
  const failedReceiptBytes = fs.readFileSync(path.join(root, receipt.path));
  const beforeUnauthorizedRetry = fs.readFileSync(manifestFile);
  const unauthorized = spawnSync(process.execPath, [entry, "retry-h5", "--artifact-root", root, "--brand", brand], { encoding: "utf8" });
  assert.match(unauthorized.stderr, /H5_RETRY_EXPLICIT_CONTINUATION_REQUIRED/);
  assert.deepEqual(fs.readFileSync(manifestFile), beforeUnauthorizedRetry);
  const receiptFile = path.join(root, receipt.path);
  const outsideFile = path.join(host, "external.json");
  fs.writeFileSync(outsideFile, "external host bytes");
  const outsideReceipt = JSON.parse(failedReceiptBytes);
  outsideReceipt.outputs.push({ path: path.relative(root, outsideFile), sha256: sha(outsideFile) });
  fs.writeFileSync(receiptFile, JSON.stringify(outsideReceipt));
  const outsideManifest = manifest();
  outsideManifest.stages[0].outputHashes = outsideReceipt.outputs;
  outsideManifest.stages[0].receiptSha256 = sha(receiptFile);
  fs.writeFileSync(manifestFile, JSON.stringify(outsideManifest));
  assert.match(call("retry-h5", "--continue-existing").stderr, /H5_RETRY_OUTPUT_OUTSIDE_MIGRATION/);
  fs.writeFileSync(receiptFile, failedReceiptBytes);
  fs.writeFileSync(manifestFile, beforeUnauthorizedRetry);
  const originalInputDirectory = path.join(root, "host-input", "opcg");
  const movedInputDirectory = path.join(temp, "moved-opcg");
  fs.renameSync(originalInputDirectory, movedInputDirectory);
  fs.symlinkSync(movedInputDirectory, originalInputDirectory);
  assert.match(call("retry-h5", "--continue-existing").stderr, /H5_RETRY_OUTPUT_SYMLINK_FORBIDDEN/);
  fs.unlinkSync(originalInputDirectory);
  fs.renameSync(movedInputDirectory, originalInputDirectory);
  const wrongStage = manifest();
  wrongStage.stages[0].stage = "designVisualQA";
  fs.writeFileSync(manifestFile, JSON.stringify(wrongStage));
  assert.match(call("retry-h5", "--continue-existing").stderr, /H5_RETRY_FAILED_STAGE_REQUIRED/);
  fs.writeFileSync(manifestFile, beforeUnauthorizedRetry);
  const historicalTimeout = manifest();
  historicalTimeout.status = "timed-out";
  historicalTimeout.timeout = { code: "DESIGN_HOST_FAST_SAFETY_LIMIT_EXCEEDED", deadlineAt: historicalTimeout.deadlineAt, observedAt: "2026-10-03T00:00:00.000Z" };
  fs.writeFileSync(manifestFile, JSON.stringify(historicalTimeout));
  const timedOutReceiptBytes = fs.readFileSync(path.join(root, receipt.path));
  const unauthorisedHistorical = call("retry-h5");
  assert.match(unauthorisedHistorical.stderr, /H5_RETRY_EXPLICIT_CONTINUATION_REQUIRED/);
  const timeoutBeforeTamper = fs.readFileSync(manifestFile);
  fs.writeFileSync(path.join(root, receipt.path), "tampered historical receipt");
  assert.match(call("retry-h5", "--continue-existing").stderr, /Receipt hash mismatch/);
  assert.deepEqual(fs.readFileSync(manifestFile), timeoutBeforeTamper);
  fs.writeFileSync(path.join(root, receipt.path), timedOutReceiptBytes);
  const retry = pass(spawnSync(process.execPath, [entry, "retry-h5", "--artifact-root", root, "--brand", brand, "--continue-existing"], { encoding: "utf8" }));
  assert.equal(retry.nextStageId, "h5DirectionGeneration-2");
  assert.deepEqual(manifest().stages[0], failed);
  assert.deepEqual(fs.readFileSync(path.join(root, receipt.path)), failedReceiptBytes);
  assert.deepEqual(fs.readFileSync(path.join(root, receipt.path)), timedOutReceiptBytes);
  assert.equal(manifest().h5Retries[0].priorStatus, "timed-out");
  assert.deepEqual(manifest().h5Retries[0].priorTimeout, historicalTimeout.timeout);
  assert.equal(manifest().timeout, null);
  assert.ok(Date.parse(retry.deadlineAt) - Date.now() <= 1200000);
  assert.ok(Date.parse(retry.deadlineAt) - Date.now() > 1190000);
  const archive = JSON.parse(fs.readFileSync(path.join(root, retry.archive.path), "utf8"));
  const archivedOutput = archive.archivedOutputs.find((item) => item.originalPath === oldOutput.path);
  const archivedHostInput = archive.archivedOutputs.find((item) => item.originalPath === hostInputBinding.path);
  assert.equal(sha(hostInputFile), hostInputBinding.sha256);
  assert.equal(sha(path.join(root, archivedHostInput.path)), hostInputBinding.sha256);
  write("h5-directions/direction-a.html", "<!doctype html><title>new candidate</title>");
  assert.equal(sha(path.join(root, archivedOutput.path)), oldOutput.sha256);
  assert.equal(sha(path.join(root, receipt.path)), receipt.sha256);
  pass(call("next"));
  const second = manifest().stages[1];
  const secondDispatch = JSON.parse(fs.readFileSync(path.join(root, second.dispatchPath), "utf8"));
  assert.equal(secondDispatch.attempt, 2);
  assert.ok(secondDispatch.requiredInputs.some((item) => item.path === retry.archive.path));
  assert.match(call("retry-h5", "--continue-existing").stderr, /H5_RETRY_FAILED_STAGE_REQUIRED/);
  fs.writeFileSync(path.join(root, archivedOutput.path), "corrupted history");
  assert.match(call("status").stderr, /Receipt hash mismatch/);
  process.stdout.write("H5 retry authorization, stage refusal, fresh dispatch and immutable failed history passed\n");
} finally {
  fs.rmSync(temp, { recursive: true, force: true });
}
if (failureVerdict === "fail") {
  const evidenceRetry = spawnSync(process.execPath, [process.argv[1], "--needs-evidence"], { encoding: "utf8" });
  assert.equal(evidenceRetry.status, 0, evidenceRetry.stderr);
  process.stdout.write(evidenceRetry.stdout);
}
