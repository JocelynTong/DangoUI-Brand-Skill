import assert from 'node:assert/strict';
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import crypto from 'node:crypto';
import { validateExpressiveGeneration } from './finalize-h5-direction-stage.mjs';
import { frozenRuntimeAssetInputs } from './validate-brand-render-kit.mjs';
const root=fs.mkdtempSync(path.join(os.tmpdir(),'expressive-production-'));
const hash=file=>crypto.createHash('sha256').update(fs.readFileSync(path.join(root,file))).digest('hex');
fs.writeFileSync(path.join(root,'source.png'),'official reference');
const input={path:'source.png',sha256:hash('source.png')};
const mod={assets:[{id:'texture',role:'environment',localPath:input.path,sourceSha256:input.sha256}]};
assert.deepEqual(frozenRuntimeAssetInputs(mod,{workspaceRoot:root,brand:'test'}),[input]);
assert.throws(()=>frozenRuntimeAssetInputs({assets:[{...mod.assets[0],sourceSha256:'0'.repeat(64)}]},{workspaceRoot:root,brand:'test'}),/HASH_MISMATCH/);
assert.throws(()=>frozenRuntimeAssetInputs({assets:[{...mod.assets[0],localPath:'../escape.png'}]},{workspaceRoot:root,brand:'test'}),/PATH_INVALID/);
const outside=fs.mkdtempSync(path.join(os.tmpdir(),'expressive-outside-'));
fs.writeFileSync(path.join(outside,'x.png'),'outside');fs.symlinkSync(path.join(outside,'x.png'),path.join(root,'linked.png'));
assert.throws(()=>frozenRuntimeAssetInputs({assets:[{...mod.assets[0],localPath:'linked.png'}]},{workspaceRoot:root,brand:'test'}),/PATH_INVALID/);
fs.rmSync(outside,{recursive:true,force:true});
const dispatch={requiredInputs:[input],fastDesignHints:{expressiveProduction:{required:true}}};
const directions=['a','b','c'].map(id=>{
 fs.writeFileSync(path.join(root,`${id}.png`),`generated ${id}`);
 return {file:path.join(root,`${id}.html`),source:`<img src="${id}.png">`,metadata:{id,expressiveGeneration:{toolCallId:`call-${id}`,prompt:`image ${id}`,inputImages:[input],asset:{path:`${id}.png`,sha256:hash(`${id}.png`)},visualDirection:`world-${id}`}}};
});
assert.equal(validateExpressiveGeneration(directions,dispatch,root,root).length,3);
fs.writeFileSync(path.join(root,'brand-mod.json'),JSON.stringify(mod));
const legacyDispatch={...dispatch,requiredInputs:[{path:'brand-mod.json',sha256:hash('brand-mod.json')}]};
assert.equal(validateExpressiveGeneration(directions,legacyDispatch,root,root).length,3);
assert.throws(()=>validateExpressiveGeneration(directions,{...legacyDispatch,requiredInputs:[{path:'brand-mod.json',sha256:'0'.repeat(64)}]},root,root),/FROZEN_BRAND_MOD_HASH_MISMATCH/);
const mutate=fn=>{const copy=structuredClone(directions);fn(copy);return copy;};
assert.throws(()=>validateExpressiveGeneration(mutate(d=>delete d[0].metadata.expressiveGeneration),dispatch,root,root),/IMAGEGEN_EXPRESSIVE_REQUIRED/);
assert.throws(()=>validateExpressiveGeneration(mutate(d=>d[1].metadata.expressiveGeneration.asset=d[0].metadata.expressiveGeneration.asset),dispatch,root,root),/NOT_USED/);
assert.throws(()=>validateExpressiveGeneration(mutate(d=>d[0].metadata.expressiveGeneration.inputImages[0].sha256='0'.repeat(64)),dispatch,root,root),/REFERENCE_NOT_FROZEN/);
assert.throws(()=>validateExpressiveGeneration(mutate(d=>d[0].metadata.expressiveGeneration.asset.sha256='0'.repeat(64)),dispatch,root,root),/HASH_MISMATCH/);
assert.throws(()=>validateExpressiveGeneration(mutate(d=>d[1].metadata.expressiveGeneration.visualDirection='world-a'),dispatch,root,root),/DIRECTIONS_MUST_DIFFER/);
assert.equal(validateExpressiveGeneration([{metadata:{id:'no-image'}}],{requiredInputs:[]},root,root).length,0);
fs.rmSync(root,{recursive:true,force:true});
console.log('expressive production tests passed');
